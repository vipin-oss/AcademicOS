"""SQLAlchemy model for the ``eval_runs`` benchmark table (Sprint-7 M3).

One immutable, append-only row per evaluation run recorded by the
evaluation runner (``run_eval_suite_across_models`` with a history wired).
Each row captures the full context needed for benchmark comparison and
regression detection:

- the model that ran — registry id plus the concrete deployed model name
  (``ModelSpec.model``, the deployment's version identity);
- the prompt asset that was active — registry id plus the version resolved
  from the ``PromptRegistry`` at run time (the registry is the single
  source of truth for versions);
- the outcome (``passed`` / ``total``) and the per-case results (name,
  passed, failure details) in deterministic suite order;
- the run timestamp.

Design notes (same doctrine as ``outbox_events`` / ``object_versions`` /
``search_documents``):

- ``run_id`` is the unique idempotency key (a UUID generated by the
  application service), so a run can never be recorded twice.
- Rows are never updated: a run's results are frozen at recording time, so
  benchmark history cannot drift stale.
- ``results`` uses the same JSONB/JSON type doctrine as the other system
  tables; ``created_at`` is the ISO-8601 string doctrine. The history
  query surface is covered by the ``(model_id, created_at)`` index.
"""
from __future__ import annotations

from sqlalchemy import Index, Integer, String
from sqlalchemy.orm import Mapped, mapped_column

from app.infrastructure.db.models.object_model import Base, TenantStampMixin
from app.infrastructure.db.types import JSONBType


class EvalRunModel(TenantStampMixin, Base):
    __tablename__ = "eval_runs"
    __table_args__ = (
        # Benchmark history queries: per-model runs, newest first.
        Index("ix_eval_runs_model_id_created_at", "model_id", "created_at"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    run_id: Mapped[str] = mapped_column(String, unique=True, nullable=False)
    model_id: Mapped[str] = mapped_column(String, nullable=False)
    # The concrete deployed model name (ModelSpec.model) at run time.
    model_version: Mapped[str] = mapped_column(String, nullable=False)
    prompt_id: Mapped[str] = mapped_column(String, nullable=False)
    prompt_version: Mapped[int] = mapped_column(Integer, nullable=False)
    passed: Mapped[int] = mapped_column(Integer, nullable=False)
    total: Mapped[int] = mapped_column(Integer, nullable=False)
    # JSONB on PostgreSQL; JSON elsewhere (same doctrine as the objects table).
    # Per-case results: [{"name", "passed", "details": [...]}, ...] in suite order.
    results: Mapped[list] = mapped_column(JSONBType, nullable=False)
    created_at: Mapped[str] = mapped_column(String, nullable=False)
